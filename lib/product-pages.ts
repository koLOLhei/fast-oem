/**
 * 商品ごとの個別ページ（/products/<slug>）の本文。
 * カードに出す短い情報は lib/site.ts の PRODUCTS、こちらは読み物としての本文を置く。
 *
 * 書くときの決まり：
 * - 価格・最低ロット・納期・寸法の上限など、当社固有の数値は確認が取れているものだけ書く
 * - 素材や製法の一般的な説明は書いてよい。対応できるかどうかが未確認の仕様は「ご相談ください」に留める
 * - 単発の注文は受けていないので、どのページでも定期発注が前提であることを崩さない
 */
import type { Faq } from './site'

export type Block = { title: string; body: string }

export type ProductPageContent = {
  /** <title>。サイト名は layout のテンプレートで付く */
  title: string
  description: string
  /** h1 */
  heading: string
  lead: string
  about: { title: string; paragraphs: string[] }
  /** 近い商品のページへの案内（「〜とは」の下にリンクで出す） */
  seeAlso?: { slug: string; text: string }[]
  /** つくりと仕様 */
  features: Block[]
  /** この商品に近い種類の一覧（例：ほかの立体シール）。個別ページが無いものをまとめて案内する */
  related?: { title: string; lead: string; items: Block[]; note: string }
  /** デザイン・データで気をつけること */
  tips: { lead: string; items: Block[] }
  /** 向いている用途 */
  uses: Block[]
  /** 定期発注にすると何が変わるか（商品ごとの一言） */
  savingsNote: Block
  /** 見積もりのときに伝えると早い情報 */
  quoteInfo: string[]
  faqs: Faq[]
}

